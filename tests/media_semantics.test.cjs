'use strict';
const {test}=require('node:test'),assert=require('node:assert/strict');
const {evaluate,HASH}=require('../verification/media-context/evaluate.cjs');
const retained=require('../verification/media-context/results.json'),result=evaluate();
for(const row of result.rows)test('frozen media semantic contract: '+row.id,()=>assert.deepEqual(row.failures,[]));
test('frozen case lineage, no network and omitted caption are explicit',()=>{
 assert.equal(result.contract_sha256,HASH);assert.equal(retained.contract_sha256,HASH);assert.equal(result.rows.length,12);assert.equal(result.network_calls,0);
 assert.deepEqual(result.rows.map(x=>x.id),retained.rows.map(x=>x.id));for(const row of result.rows)assert.equal(row.caption_omitted,true);
});
test('camera, software and missing fields cannot establish origin',()=>{
 const camera=result.rows.find(x=>x.id==='camera-present').result;
 assert.match(camera.questions.find(q=>q.id==='camera:unverified').text,/does not establish.*camera original/);
 const software=result.rows.find(x=>x.id==='editor-software').result;
 assert.match(software.questions.find(q=>q.id==='software:unverified').text,/does not establish.*generated by AI/);
 const missing=result.rows.find(x=>x.id==='camera-absent').result;
 assert.match(missing.facts.find(f=>f[0].startsWith('Embedded camera'))[1],/proves neither origin nor authenticity/);
});
test('GPS reports presence only and does not prove privacy or scene location',()=>{
 for(const row of result.rows.filter(x=>x.result))assert.equal(row.result.facts.filter(f=>f[0].startsWith('GPS')).length,1);
 const present=result.rows.find(x=>x.id==='gps-present').result;
 assert.match(present.questions.find(q=>q.id==='gps:privacy').text,/no scene location is established/);
 assert.match(present.questions.find(q=>q.id==='gps:privacy').text,/no location lookup ran/);
 assert.doesNotMatch(JSON.stringify(present),/coordinates (?:were|are) not inspected/i);
 assert.match(present.facts.find(f=>f[0].startsWith('GPS'))[1],/coordinates are not displayed or returned/);
 const absent=result.rows.find(x=>x.id==='gps-absent').result;
 assert.match(absent.facts.find(f=>f[0].startsWith('GPS'))[1],/does not establish location privacy/);
});
test('future time and display orientation remain file context, never caption truth',()=>{
 const future=result.rows.find(x=>x.id==='date-future').result;
 assert.match(future.questions.find(q=>q.id==='date:future').text,/does not disprove the caption/);
 const orientation=result.rows.find(x=>x.id==='orientation').result;
 assert.match(orientation.facts.find(f=>f[0]==='Encoded dimensions')[1],/800 × 600/);
 assert.match(orientation.facts.find(f=>f[0]==='Display dimensions')[1],/600 × 800.*orientation applied/);
 for(const row of result.rows.filter(x=>x.result))assert.match(row.result.questions.find(q=>q.id==='origin:separate').text,/No origin model, signed-provenance verification, reverse image search or location lookup ran/);
});
